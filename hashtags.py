MAP={'جنگ':'#جنگ','ایران':'#ایران','تحریم':'#تحریم','توافق':'#توافق','اقتصاد':'#اقتصاد','دلار':'#دلار','نفت':'#نفت','بورس':'#بورس','انتخابات':'#انتخابات','مجلس':'#مجلس','دولت':'#دولت','آمریکا':'#آمریکا','اسرائیل':'#اسرائیل','غزه':'#غزه','لبنان':'#لبنان','مذاکره':'#مذاکرات','برجام':'#برجام'}
def make_hashtags(title,text):
    s=f'{title} {text}'; tags=[]
    for k,v in MAP.items():
        if k in s and v not in tags: tags.append(v)
        if len(tags)>=2: break
    return ' '.join((tags or ['#خبر','#ایران'])[:2]) if len(tags)>1 else tags[0]+' #خبر'
